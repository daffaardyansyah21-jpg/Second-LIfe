// ============================================================================
// SECOND LIFE — Zero-Dependency Vercel Serverless Builder
// Converts src/**/*.ts into pure ES Module .js files under api/_app/ and
// creates api/index.js so Vercel runs without TypeScript extension issues.
// ============================================================================

import fs from 'node:fs';
import path from 'node:path';
import module from 'node:module';

const projectRoot = process.cwd();
const srcDir = path.join(projectRoot, 'src');
const outAppDir = path.join(projectRoot, 'api', '_app');

function cleanAndEnsureDir(dir) {
  if (fs.existsSync(dir)) {
    fs.rmSync(dir, { recursive: true, force: true });
  }
  fs.mkdirSync(dir, { recursive: true });
}

function compileDirectory(currentSrc, currentOut) {
  fs.mkdirSync(currentOut, { recursive: true });
  const entries = fs.readdirSync(currentSrc, { withFileTypes: true });

  for (const entry of entries) {
    const srcPath = path.join(currentSrc, entry.name);
    if (entry.isDirectory()) {
      compileDirectory(srcPath, path.join(currentOut, entry.name));
    } else if (entry.isFile() && entry.name.endsWith('.ts')) {
      const tsCode = fs.readFileSync(srcPath, 'utf-8');
      let jsCode = module.stripTypeScriptTypes(tsCode, { mode: 'strip' });

      // Rewrite relative .ts imports to .js for standard Node ES Modules on Vercel
      jsCode = jsCode.replace(
        /(from\s+['"])(\.\.?\/[^'"]+)\.ts(['"])/g,
        '$1$2.js$3'
      );

      const outFileName = entry.name.replace(/\.ts$/, '.js');
      fs.writeFileSync(path.join(currentOut, outFileName), jsCode, 'utf-8');
    }
  }
}

if (typeof module.stripTypeScriptTypes === 'function') {
  cleanAndEnsureDir(outAppDir);
  compileDirectory(srcDir, outAppDir);

  const apiIndexPath = path.join(projectRoot, 'api', 'index.js');
  const apiIndexContent = `// Vercel Serverless Entrypoint — Auto-generated by scripts/build-vercel.mjs
import { requestHandler } from './_app/server.js';

export default async function handler(req, res) {
  return requestHandler(req, res);
}
`;
  fs.writeFileSync(apiIndexPath, apiIndexContent, 'utf-8');
  console.log('Successfully built Vercel serverless entrypoint at api/index.js');
} else {
  console.log('Using pre-compiled Vercel serverless bundle in api/index.js');
}
